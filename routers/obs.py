from fastapi import APIRouter, HTTPException, Header
from pydantic import BaseModel
import os
import re
import traceback
import sys
from services.pdf_extractor import extract_text_from_r2
from services.hwp_extractor import extract_text_from_bytes as extract_hwp_text
from services.r2_client import download_file
from services.parser import parse_obs_sections, extract_meta, check_gate
from services.section_refiner import refine_sections
from services.quiz_generator import generate_quizzes, regenerate_single_quiz

router = APIRouter()

# 내부 전용 서비스 — 백엔드 중계만 호출하도록 공유 시크릿으로 보호한다.
# 미설정 시(운영 오설정) 열려버리지 않도록 호출을 거부(fail-closed)한다.
INTERNAL_API_TOKEN = os.getenv("INTERNAL_API_TOKEN")

# 허용 R2 키 패턴 — (선택적 환경 prefix 1세그먼트) + obs/ + 단일 파일명 + .pdf/.hwp.
# 백엔드 StorageService가 환경별 key-prefix(dev="dev/", prod="")를 붙이므로
# dev/obs/<uuid>.pdf 형태도 허용한다. prefix 세그먼트엔 점(.) 불가 → 경로 탈출 차단.
_R2_KEY_PATTERN = re.compile(r"^([A-Za-z0-9_-]+/)?obs/[A-Za-z0-9._-]+\.(pdf|hwp)$")


def verify_internal_token(x_internal_token: str | None):
    if not INTERNAL_API_TOKEN:
        # 토큰 미설정이면 안전하게 거부 (백엔드·AI 양쪽에 동일 INTERNAL_API_TOKEN 필요)
        raise HTTPException(status_code=503, detail="service_unconfigured")
    if x_internal_token != INTERNAL_API_TOKEN:
        raise HTTPException(status_code=401, detail="unauthorized")


class ProcessRequest(BaseModel):
    r2_key: str


class ProcessResponse(BaseModel):
    sections: list
    summary: list[str]
    quizzes: list
    # 이하 추가 필드 — 백엔드(Jackson 3, FAIL_ON_UNKNOWN_PROPERTIES 기본 false)는 모르면 무시한다.
    meta: dict = {}       # title / biblePassage / publishedDate (못 찾으면 null)
    gate: dict = {}       # templateOk / missingLines / warnings
    generator: str = ""   # 퀴즈를 실제로 만든 모델 (Claude 실패 시 Gemini 폴백 여부 확인용)


@router.post("/process", response_model=ProcessResponse)
def process_obs(request: ProcessRequest, x_internal_token: str | None = Header(default=None)):
    verify_internal_token(x_internal_token)

    # r2_key 검증 — 허용 패턴 외(임의 버킷 객체)면 거부
    if not _R2_KEY_PATTERN.match(request.r2_key):
        raise HTTPException(status_code=400, detail="invalid_r2_key")

    try:
        print(f"[AI] Processing R2 Key: {request.r2_key}", file=sys.stderr)
        is_hwp = request.r2_key.endswith(".hwp")
        if is_hwp:
            # HWP는 문단 단위로 깨끗하게 나온다 → 줄 이어붙이기·AI 후보정 없이 규칙 파서만.
            # (refiner는 PoC에서 8개 중 3개의 구조를 훼손했다: intro 헤더 오염, 해설→항목 승격)
            text = extract_hwp_text(download_file(request.r2_key))
            sections = parse_obs_sections(text, paragraph_mode=True)
        else:
            text = extract_text_from_r2(request.r2_key)
            sections = parse_obs_sections(text)
            # PDF는 줄바꿈 잡음이 있어 AI 후보정을 유지한다. 실패·이상 시 초안 그대로.
            sections = refine_sections(text, sections)
        print(f"[AI] {'HWP' if is_hwp else 'PDF'} text length: {len(text)}, sections: {len(sections)}", file=sys.stderr)

        gate = check_gate(text, sections)
        if gate["warnings"]:
            print(f"[AI] gate warnings: {gate['warnings']}", file=sys.stderr)

        meta = extract_meta(text)
        ai_result = generate_quizzes(sections, title=meta["title"])

        quizzes = ai_result.get("quizzes", [])
        summary = ai_result.get("summaries", [])
        generator = ai_result.get("generator", "")

        print(f"[AI] Generated by {generator}: summaries {len(summary)}, quizzes {len(quizzes)}", file=sys.stderr)

        return ProcessResponse(
            sections=sections, summary=summary, quizzes=quizzes,
            meta=meta, gate=gate, generator=generator,
        )
    except HTTPException:
        raise
    except Exception as e:
        # 내부 오류 원문은 서버 로그에만 남기고, 신뢰 경계 밖(응답)으로는 일반 메시지만 반환
        print(f"[AI] ERROR: {str(e)}", file=sys.stderr)
        traceback.print_exc()
        raise HTTPException(status_code=500, detail="processing_failed")


class RegenerateQuizRequest(BaseModel):
    sections: list
    step_number: int
    current_question: str | None = None
    instruction: str | None = None
    other_questions: list[str] | None = None


class RegenerateQuizResponse(BaseModel):
    quiz: dict


@router.post("/regenerate-quiz", response_model=RegenerateQuizResponse)
def regenerate_quiz(request: RegenerateQuizRequest, x_internal_token: str | None = Header(default=None)):
    """검수 화면에서 특정 문제(step) 1개만 다시 생성. 유형 고정 + 관리자 지침 반영 + 중복 회피.
    백엔드가 저장된 sections를 실어 중계하므로 콘텐츠 저장 여부와 무관하게 동작한다."""
    verify_internal_token(x_internal_token)

    if request.step_number not in (1, 2, 3):
        raise HTTPException(status_code=400, detail="invalid_step_number")
    if not request.sections:
        raise HTTPException(status_code=400, detail="empty_sections")

    try:
        print(f"[AI] Regenerate quiz step={request.step_number}", file=sys.stderr)
        quiz = regenerate_single_quiz(
            sections=request.sections,
            step_number=request.step_number,
            current_question=request.current_question,
            instruction=request.instruction,
            other_questions=request.other_questions,
        )
        return RegenerateQuizResponse(quiz=quiz)
    except HTTPException:
        raise
    except Exception as e:
        print(f"[AI] ERROR (regenerate): {str(e)}", file=sys.stderr)
        traceback.print_exc()
        raise HTTPException(status_code=500, detail="regenerate_failed")
